"""
utils/region_matcher.py
根据医院名称自动匹配所在区域（浦东/虹口/杨浦/闵行等）
"""

REGION_KEYWORDS = {
    '浦东新区': ['浦东', '第七人民', '七院', '光明中医', '公利', '周浦', '东明', '东方医院', '仁济'],
    '虹口区': ['虹口', '公卫-虹口', '中西医'],
    '杨浦区': ['杨浦', '长海', '新华'],
    '闵行区': ['闵行', '五院', '儿科'],
    '松江区': ['松江', '第一人民医院南院'],
    '嘉定区': ['嘉定', '瑞金北院'],
    '金山区': ['金山', '公共卫生临床中心'],
    '青浦区': ['青浦', '中山青浦'],
    '奉贤区': ['奉贤', '奉城'],
    '崇明区': ['崇明', '新华崇明'],
    '黄浦区': ['黄浦', '九院', '瑞金'],
    '徐汇区': ['徐汇', '中山', '龙华', '六院'],
    '长宁区': ['长宁', '同仁', '光华'],
    '静安区': ['静安', '华山', '华东'],
    '普陀区': ['普陀', '同济'],
    '其他': [],
}


def match_region(hospital_name):
    """根据医院名称匹配所在区域"""
    if not hospital_name:
        return '其他'
    for region, keywords in REGION_KEYWORDS.items():
        for kw in keywords:
            if kw in hospital_name:
                return region
    return '其他'
